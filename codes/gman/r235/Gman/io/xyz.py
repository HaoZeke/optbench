# Function to save a xyz file
##################################################
def savexyz(p,filename,w='w'):
  xyz=open(filename,w)
  print(p.NumAtoms, file=xyz)
  try: print(p.XYZHeader, file=xyz)
  except: print("Generated by Gman", file=xyz)
  for i in range(p.NumAtoms):
    print(("%s" % p.AtomType[p.Type[i]])+" "+" ".join(['%15.8f' % s for s in p.R[i]]), file=xyz)
