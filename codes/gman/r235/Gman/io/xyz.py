import numpy
import Gman.data as data
##################################################
# Function to load a xyz file
##################################################
def loadxyz(p,filename):
  p.PointType='XYZ'
  xyz=open(filename,'r')
  NumAtoms=numpy.array([ int(f) for f in xyz.readline().split() ])
  p.NumAtoms=NumAtoms[0]
  p.XYZHeader=xyz.readline()[:-1]
  p.Type=numpy.zeros((p.NumAtoms))
  p.Box=numpy.identity((3),'d')
  p.R=numpy.zeros((p.NumAtoms,3),'d')
  p.Mass=numpy.ones((p.NumAtoms),'d')
  p.MassD=numpy.ones((p.NumAtoms,3),'d')
  p.Free=numpy.ones((p.NumAtoms))
  p.FreeD=numpy.ones((p.NumAtoms,3))
#  read in lines, but we don't know how many types we have
  p.NumAtomTypes=1
  NumAtom=[0]
  p.AtomType=[]
  for i in range(p.NumAtoms):
    line=xyz.readline().split()
    type=line[0]
    if(i==0): p.AtomType.append(type)
    for j in range(p.NumAtomTypes):
      foundtype=0
      if(type == p.AtomType[j]):
        typenum=j
        foundtype=1
        break
    if(not foundtype):
      p.AtomType.append(type)
      NumAtom.append(0)
      typenum=p.NumAtomTypes
      p.NumAtomTypes+=1
    NumAtom[typenum]+=1
    p.Type[i]=typenum
    p.R[i]=numpy.array([ float(f) for f in line[1:4] ])
  p.NumAtom=numpy.asarray(NumAtom,numpy.int)
  p.MassType=numpy.ones((p.NumAtomTypes),'d')
  
