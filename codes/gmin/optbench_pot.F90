! OptBench harness client for GMIN.
! Compiled into the GMIN binary by codes/gmin/build.sh.
! OPTBENCH_POTPORT selects the server. An unset port leaves GMIN on its own LJ.

MODULE OPTBENCH_POT
   USE ISO_C_BINDING, ONLY: C_INT, C_CHAR, C_NULL_CHAR, C_INT64_T
   USE ISO_FORTRAN_ENV, ONLY: REAL64
   IMPLICIT NONE
   PRIVATE
   PUBLIC :: OPTBENCH_ACTIVE, OPTBENCH_LJ

   LOGICAL, SAVE :: READY = .FALSE.
   LOGICAL, SAVE :: ACTIVE = .FALSE.
   INTEGER(C_INT), SAVE :: FD = -1
   INTEGER, SAVE :: PORT = 0
   CHARACTER(LEN=128), SAVE :: HOST = "127.0.0.1"
   INTEGER(C_INT), ALLOCATABLE, SAVE :: XBUF(:), VBUF(:)

   INTERFACE
      FUNCTION SOCK_CONNECT_C(HOST_C, PORT_C) BIND(C, NAME="sock_connect_c")
         IMPORT C_INT, C_CHAR
         CHARACTER(KIND=C_CHAR), INTENT(IN) :: HOST_C(*)
         INTEGER(C_INT), VALUE :: PORT_C
         INTEGER(C_INT) :: SOCK_CONNECT_C
      END FUNCTION SOCK_CONNECT_C

      FUNCTION SOCK_SEND_C(FD_C, BUF, NBYTES) BIND(C, NAME="sock_send_c")
         IMPORT C_INT
         INTEGER(C_INT), VALUE :: FD_C, NBYTES
         INTEGER(C_INT), INTENT(IN) :: BUF(*)
         INTEGER(C_INT) :: SOCK_SEND_C
      END FUNCTION SOCK_SEND_C

      FUNCTION SOCK_RECV_C(FD_C, BUF, NBYTES) BIND(C, NAME="sock_recv_c")
         IMPORT C_INT
         INTEGER(C_INT), VALUE :: FD_C, NBYTES
         INTEGER(C_INT), INTENT(INOUT) :: BUF(*)
         INTEGER(C_INT) :: SOCK_RECV_C
      END FUNCTION SOCK_RECV_C

      SUBROUTINE OPTBENCH_EXIT(CODE) BIND(C, NAME="exit")
         IMPORT C_INT
         INTEGER(C_INT), VALUE :: CODE
      END SUBROUTINE OPTBENCH_EXIT
   END INTERFACE

CONTAINS

   LOGICAL FUNCTION OPTBENCH_ACTIVE()
      IF (.NOT. READY) CALL OPTBENCH_INIT()
      OPTBENCH_ACTIVE = ACTIVE
   END FUNCTION OPTBENCH_ACTIVE

   SUBROUTINE OPTBENCH_INIT()
      CHARACTER(LEN=128) :: TEXT
      INTEGER :: LENGTH, STATUS, IOS

      READY = .TRUE.
      ACTIVE = .FALSE.
      CALL GET_ENVIRONMENT_VARIABLE("OPTBENCH_POTPORT", TEXT, LENGTH, STATUS)
      IF (STATUS /= 0 .OR. LENGTH <= 0) RETURN
      READ(TEXT(1:LENGTH), *, IOSTAT=IOS) PORT
      IF (IOS /= 0 .OR. PORT <= 0) THEN
         WRITE(*, "(A)") "optbench> OPTBENCH_POTPORT is not a port"
         CALL OPTBENCH_HALT(2)
      END IF
      CALL GET_ENVIRONMENT_VARIABLE("OPTBENCH_POTHOST", TEXT, LENGTH, STATUS)
      IF (STATUS == 0 .AND. LENGTH > 0) HOST = TEXT(1:LENGTH)
      ACTIVE = .TRUE.
   END SUBROUTINE OPTBENCH_INIT

   SUBROUTINE OPTBENCH_CONNECT()
      CHARACTER(KIND=C_CHAR, LEN=129) :: HOST_C
      INTEGER :: I

      IF (FD >= 0) RETURN
      HOST_C = C_NULL_CHAR
      DO I = 1, LEN_TRIM(HOST)
         HOST_C(I:I) = HOST(I:I)
      END DO
      HOST_C(LEN_TRIM(HOST)+1:LEN_TRIM(HOST)+1) = C_NULL_CHAR
      FD = SOCK_CONNECT_C(HOST_C, INT(PORT, C_INT))
      IF (FD < 0) THEN
         WRITE(*, "(A,A,A,I0)") "optbench> connect failed ", TRIM(HOST), ":", PORT
         CALL OPTBENCH_HALT(2)
      END IF
   END SUBROUTINE OPTBENCH_CONNECT

   SUBROUTINE OPTBENCH_LJ(NATOMS, X, V, ENERGY, GTEST)
      INTEGER, INTENT(IN) :: NATOMS
      REAL(REAL64), INTENT(IN) :: X(3*NATOMS)
      REAL(REAL64), INTENT(OUT) :: V(3*NATOMS)
      REAL(REAL64), INTENT(OUT) :: ENERGY
      LOGICAL, INTENT(IN) :: GTEST
      INTEGER(C_INT) :: HEADER(2), STATUS_BUF(1), IBUF(2)
      INTEGER(C_INT64_T) :: NCALLS
      INTEGER :: RC, NCOORD
      REAL(REAL64) :: EBUF(1)

      NCOORD = 3*NATOMS
      CALL OPTBENCH_CONNECT()
      HEADER(1) = 1
      HEADER(2) = NATOMS
      RC = INT(SOCK_SEND_C(FD, HEADER, 8))
      IF (RC /= 0) CALL OPTBENCH_FAIL("send header")
      IF (.NOT. ALLOCATED(XBUF) .OR. SIZE(XBUF) /= 2*NCOORD) THEN
         IF (ALLOCATED(XBUF)) DEALLOCATE(XBUF)
         IF (ALLOCATED(VBUF)) DEALLOCATE(VBUF)
         ALLOCATE(XBUF(2*NCOORD), VBUF(2*NCOORD))
      END IF
      XBUF = TRANSFER(X, XBUF)
      RC = INT(SOCK_SEND_C(FD, XBUF, NCOORD*8))
      IF (RC /= 0) CALL OPTBENCH_FAIL("send coordinates")
      RC = INT(SOCK_RECV_C(FD, STATUS_BUF, 4))
      IF (RC /= 0) CALL OPTBENCH_FAIL("recv status")
      CALL OPTBENCH_RECV_ENERGY(EBUF, RC)
      IF (RC /= 0) CALL OPTBENCH_FAIL("recv energy")
      RC = INT(SOCK_RECV_C(FD, IBUF, 8))
      IF (RC /= 0) CALL OPTBENCH_FAIL("recv calls")
      NCALLS = TRANSFER(IBUF, NCALLS)
      RC = INT(SOCK_RECV_C(FD, VBUF, NCOORD*8))
      IF (RC /= 0) CALL OPTBENCH_FAIL("recv gradient")
      IF (GTEST) THEN
         V = TRANSFER(VBUF, V)
      ELSE
         V = 0.0_REAL64
      END IF
      ENERGY = EBUF(1)
      IF (STATUS_BUF(1) == 1) CALL OPTBENCH_HALT(2)
      IF (STATUS_BUF(1) /= 0) THEN
         WRITE(*, "(A,I0)") "optbench> server status ", STATUS_BUF(1)
         CALL OPTBENCH_HALT(2)
      END IF
      IF (NCALLS < 0) CALL OPTBENCH_HALT(2)
   END SUBROUTINE OPTBENCH_LJ

   SUBROUTINE OPTBENCH_RECV_ENERGY(EBUF, RC)
      REAL(REAL64), INTENT(OUT) :: EBUF(1)
      INTEGER, INTENT(OUT) :: RC
      INTEGER(C_INT) :: IBUF(2)

      RC = INT(SOCK_RECV_C(FD, IBUF, 8))
      IF (RC == 0) EBUF = TRANSFER(IBUF, EBUF)
   END SUBROUTINE OPTBENCH_RECV_ENERGY

   SUBROUTINE OPTBENCH_FAIL(WHAT)
      CHARACTER(LEN=*), INTENT(IN) :: WHAT
      WRITE(*, "(A,A)") "optbench> socket ", WHAT
      CALL OPTBENCH_HALT(2)
   END SUBROUTINE OPTBENCH_FAIL

   SUBROUTINE OPTBENCH_HALT(CODE)
      INTEGER, INTENT(IN) :: CODE
#ifdef GMIN_MPI
      INCLUDE "mpif.h"
      INTEGER :: IERR
      CALL MPI_ABORT(MPI_COMM_WORLD, CODE, IERR)
#endif
      CALL OPTBENCH_EXIT(INT(CODE, C_INT))
   END SUBROUTINE OPTBENCH_HALT

END MODULE OPTBENCH_POT
