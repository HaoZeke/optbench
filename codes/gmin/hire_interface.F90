! Stub HiRE interface. The Wales tarball omits HiRE/hire_interface.F90.
! Basin-hopping on Lennard-Jones does not call these routines.
! They exist so gminlib can compile.

MODULE HIRE_INTERFACE
   USE ISO_FORTRAN_ENV, ONLY: REAL64
   IMPLICIT NONE
CONTAINS

   SUBROUTINE HIRE_INITIALISE(TOP, SCALE, NATOMS)
      CHARACTER(LEN=*), INTENT(IN) :: TOP, SCALE
      INTEGER, INTENT(INOUT) :: NATOMS
   END SUBROUTINE HIRE_INITIALISE

   SUBROUTINE TERMINATE_HIRE()
   END SUBROUTINE TERMINATE_HIRE

   SUBROUTINE DUMP_PDB(N, X, NAME, FLAG)
      INTEGER, INTENT(IN) :: N
      REAL(REAL64), INTENT(IN) :: X(N)
      CHARACTER(LEN=*), INTENT(IN) :: NAME
      LOGICAL, INTENT(IN) :: FLAG
   END SUBROUTINE DUMP_PDB

   SUBROUTINE PASS_PARTICLE_NAMES(NATOMS, NAMES)
      INTEGER, INTENT(IN) :: NATOMS
      CHARACTER(LEN=*), INTENT(INOUT) :: NAMES(NATOMS)
   END SUBROUTINE PASS_PARTICLE_NAMES

   SUBROUTINE PASS_HIRE_MASSES(NATOMS, MASS)
      INTEGER, INTENT(IN) :: NATOMS
      REAL(REAL64), INTENT(INOUT) :: MASS(NATOMS)
   END SUBROUTINE PASS_HIRE_MASSES

   SUBROUTINE SETUP_SAXS(SAXST, SAXSPRINT, SAXSMODULT, SAXSINVSIG, SAXSMAX, &
                         SAXSSOLT, REFINET, WATRAD, NWATLAY)
      LOGICAL, INTENT(IN) :: SAXST, SAXSPRINT, SAXSMODULT, SAXSSOLT, REFINET
      REAL(REAL64), INTENT(IN) :: SAXSINVSIG, SAXSMAX, WATRAD
      INTEGER, INTENT(IN) :: NWATLAY
   END SUBROUTINE SETUP_SAXS

   SUBROUTINE HIRE_HB_INIT()
   END SUBROUTINE HIRE_HB_INIT

   SUBROUTINE CALL_HBDAT(N, HBX)
      INTEGER, INTENT(IN) :: N
      REAL(REAL64), INTENT(IN) :: HBX(N)
   END SUBROUTINE CALL_HBDAT

   SUBROUTINE HIRE_ENERGY_GRAD(N, X, ENERGY, GRAD, FLAG)
      INTEGER, INTENT(IN) :: N
      REAL(REAL64), INTENT(IN) :: X(N)
      REAL(REAL64), INTENT(OUT) :: ENERGY
      REAL(REAL64), INTENT(OUT) :: GRAD(N)
      LOGICAL, INTENT(IN) :: FLAG
      ENERGY = 0.0_REAL64
      GRAD = 0.0_REAL64
   END SUBROUTINE HIRE_ENERGY_GRAD

   SUBROUTINE HIRE_NUMHESS(N, X, DELTA, HESSIAN)
      INTEGER, INTENT(IN) :: N
      REAL(REAL64), INTENT(IN) :: X(N)
      REAL(REAL64), INTENT(IN) :: DELTA
      REAL(REAL64), INTENT(INOUT) :: HESSIAN(:, :)
   END SUBROUTINE HIRE_NUMHESS

END MODULE HIRE_INTERFACE
