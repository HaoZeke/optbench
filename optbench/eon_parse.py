def xyz_to_con(text: str, *, box: float | None = None) -> str:
    """Extended XYZ to a free-cluster ``.con``.

    The first line is the atom count. The second line is a comment.
    Each later line is ``element x y z``. Lennard-Jones depends on
    distances, so the cluster is centered in a cube. The default cube
    is at least 100 and at least 80 past the span, which puts periodic
    images outside a cutoff of 40.
    """
    lines = [line.strip() for line in text.splitlines() if line.strip()]
    if len(lines) < 3:
        raise ValueError("xyz needs a count, a comment, and coordinates")
    natoms = int(lines[0].split()[0])
    body = lines[2 : 2 + natoms]
    if len(body) != natoms:
        raise ValueError(f"xyz declares {natoms} atoms and has {len(body)}")
    coords: list[tuple[float, float, float]] = []
    for line in body:
        parts = line.split()
        if len(parts) < 4:
            raise ValueError(f"xyz coordinate needs element x y z: {line}")
        coords.append((float(parts[1]), float(parts[2]), float(parts[3])))
    xs = [point[0] for point in coords]
    ys = [point[1] for point in coords]
    zs = [point[2] for point in coords]
    span = max(max(xs) - min(xs), max(ys) - min(ys), max(zs) - min(zs))
    side = box if box is not None else max(100.0, span + 80.0)
    shift = (
        side / 2.0 - sum(xs) / natoms,
        side / 2.0 - sum(ys) / natoms,
        side / 2.0 - sum(zs) / natoms,
    )
    rows = [
        "Generated by optbench",
        "0.0000 TIME",
        f"{side:.6f}  {side:.6f}  {side:.6f}",
        "90.000000   90.000000   90.000000",
        "0 0",
        "0 0 0",
        "1",
        str(natoms),
        "1.00000",
        "H",
        "Coordinates of Component 1",
    ]
    for index, (x, y, z) in enumerate(coords):
        rows.append(
            f"  {x + shift[0]:.8f}   {y + shift[1]:.8f}   {z + shift[2]:.8f}  0     {index}"
        )
    return "\n".join(rows) + "\n"


def flat_floats(text: str) -> list[float]:
    """Floats in a mode file. Blank lines and ``#`` comments are skipped."""
    values: list[float] = []
    for line in text.splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        for token in stripped.split():
            values.append(float(token))
    return values


def abs_overlap(left: list[float], right: list[float]) -> float:
    """Absolute dot product, without renormalizing either vector."""
    if not left or len(left) != len(right):
        raise ValueError("mode vectors must be the same non-zero length")
    return abs(sum(a * b for a, b in zip(left, right)))


def first_success(evaluate, *, limit: int = 256):
    """Smallest positive integer ``k`` for which ``evaluate(k)`` succeeds.

    ``evaluate`` returns ``(ok, payload)``. The search tries 1, then
    doubles until a success or ``limit``, then bisects. The returned
    payload is the one from the smallest successful ``k``. ``k`` is
    ``None`` when nothing up to ``limit`` succeeds; the payload is then
    the last attempt.
    """
    if limit < 1:
        raise ValueError("limit must be positive")

    def attempt(k: int):
        ok, payload = evaluate(k)
        return bool(ok), payload

    ok, payload = attempt(1)
    if ok:
        return 1, payload
    if limit == 1:
        return None, payload
    lo = 1
    hi = 1
    while not ok and hi < limit:
        lo = hi
        hi = min(limit, hi * 2)
        ok, payload = attempt(hi)
    if not ok:
        return None, payload
    best = (hi, payload)
    while lo + 1 < hi:
        mid = (lo + hi) // 2
        ok, payload = attempt(mid)
        if ok:
            hi = mid
            best = (mid, payload)
        else:
            lo = mid
    return best


def saddle_progress(text: str, *, target: int = 27, barrier: float = 1.5) -> dict:
    """Cost of reaching ``target`` good saddles below ``barrier``.

    This is the 2014 ``done.py`` rule. The first two lines are the
    header. Each later line contributes ``sad-fcs + mins-fcs``. A result
    token containing ``good`` is a unique saddle. A result token
    containing ``Connected`` increments the not-connected count, which
    is how that script matches ``Not Connected``. That label is the
    r2205 ``Matter::compare`` rejection in ``optbench.connection``.
    ``fraction_connected`` is ``done_fraction``. Lines after the
    target are ignored. ``reached`` is false when the file ends first.
    """
    if target <= 0:
        raise ValueError("target must be positive")
    lines = text.splitlines()
    force_calls = 0
    unique = 0
    not_connected = 0
    searches = 0
    found = 0
    reached = False
    for line in lines[2:]:
        fields = line.split()
        if len(fields) < 6:
            continue
        searches += 1
        height = float(fields[2])
        force_calls += int(fields[4]) + int(fields[5])
        result = fields[-1]
        if "good" in result:
            unique += 1
        if result_is_not_connected(result):
            not_connected += 1
        if "good" in result and height < barrier:
            found += 1
            if found >= target:
                reached = True
                break
    fraction = None
    if searches:
        fraction = done_fraction(searches, not_connected)
    return {
        "reached": reached,
        "force_calls": force_calls,
        "unique_saddles": unique,
        "fraction_connected": fraction,
        "total_searches": searches,
        "qualifying": found,
    }
